#!/usr/bin/env python3
"""Audit the three Phase 3 gene sources and freeze their deterministic union."""

from __future__ import annotations

import argparse
import csv
import hashlib
import re
from pathlib import Path


OMIM_PROTOCOL_SEEDS = (
    "FBN1", "ACTA2", "COL3A1", "COL5A1", "EFEMP2", "EMILIN1", "ENPP1",
    "LOX", "MFAP5", "MYLK", "PLOD3", "PRKG1", "SMAD2", "SMAD3", "TGFB2",
    "TGFB3", "TGFBR1", "TGFBR2", "THBS2", "THSD4",
)

UREMIC_PROTOCOL_SEEDS = (
    "ELN", "COL1A1", "COL3A1", "MMP1", "MMP2", "MMP9", "TIMP1", "BGN",
    "MGP", "RUNX2", "SPP1", "BMP2", "IBSP", "NOX4", "NFKB1", "NFE2L2",
    "ACE", "AGTR1", "AGT", "TGFB1", "SMAD3", "LOX", "TGFBR1", "TGFBR2",
    "ENG", "BMP4",
)

SYMBOL_RE = re.compile(r"^[A-Z][A-Z0-9-]*$")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_geo(path: Path) -> list[str]:
    with path.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames != ["gene"]:
            raise ValueError(f"expected exactly one field named gene; got {reader.fieldnames}")
        genes = [row["gene"].strip() for row in reader]
    if not genes or any(not gene for gene in genes):
        raise ValueError("Phase 1 intersection contains empty gene values")
    if len(genes) != len(set(genes)):
        raise ValueError("Phase 1 intersection contains duplicate genes")
    if genes != sorted(genes):
        raise ValueError("Phase 1 intersection is not deterministically sorted")
    return genes


def validate_symbols(label: str, genes: tuple[str, ...] | list[str]) -> None:
    invalid = [gene for gene in genes if not SYMBOL_RE.fullmatch(gene)]
    if invalid:
        raise ValueError(f"{label} contains invalid symbol syntax: {invalid}")
    if len(genes) != len(set(genes)):
        raise ValueError(f"{label} contains duplicate genes")


def write_outputs(root: Path) -> None:
    geo_path = root / "project/results/geo/intersection_genes.csv"
    protocol_path = root / "phase3_network.md"
    output_dir = root / "project/results/network"
    output_dir.mkdir(parents=True, exist_ok=True)

    geo = read_geo(geo_path)
    validate_symbols("Phase 1 intersection", geo)
    validate_symbols("OMIM protocol seeds", OMIM_PROTOCOL_SEEDS)
    validate_symbols("uremic protocol seeds", UREMIC_PROTOCOL_SEEDS)

    union = sorted(set(geo) | set(OMIM_PROTOCOL_SEEDS) | set(UREMIC_PROTOCOL_SEEDS))
    union_path = output_dir / "union_genes.txt"
    union_path.write_text("".join(f"{gene}\n" for gene in union), encoding="utf-8")

    membership_path = output_dir / "gene_source_audit.tsv"
    with membership_path.open("w", newline="", encoding="utf-8") as handle:
        fields = ["gene", "phase1_intersection", "omim_protocol_seed", "uremic_protocol_seed"]
        writer = csv.DictWriter(handle, fieldnames=fields, delimiter="\t")
        writer.writeheader()
        for gene in union:
            writer.writerow({
                "gene": gene,
                "phase1_intersection": int(gene in geo),
                "omim_protocol_seed": int(gene in OMIM_PROTOCOL_SEEDS),
                "uremic_protocol_seed": int(gene in UREMIC_PROTOCOL_SEEDS),
            })

    union_hash = sha256(union_path)
    (output_dir / "union_genes.sha256").write_text(
        f"{union_hash}  union_genes.txt\n", encoding="utf-8"
    )

    omim_novel = sorted(set(OMIM_PROTOCOL_SEEDS) - set(geo))
    uremic_novel = sorted(set(UREMIC_PROTOCOL_SEEDS) - set(geo))
    report = f"""# Phase 3 gene-set source and field audit

Date: 2026-08-08

## Frozen result

- Union: {len(union)} unique, lexicographically sorted human-style gene symbols.
- SHA-256: `{union_hash}`.
- Membership table: `gene_source_audit.tsv`; each source is a separate Boolean field, so overlaps are retained rather than overwritten.

## Source audit

| Source | Input/field | Rows / unique | Provenance status | Inclusion rule |
|---|---|---:|---|---|
| Phase 1 intersection | `project/results/geo/intersection_genes.csv`; exact field `gene` | {len(geo)} / {len(set(geo))} | VERIFIED locally: generated by `phase1_mapping_enrichment.R` as the sorted intersection of significant rat-uremic and mouse-AAD DEGs after human 1:1 ortholog mapping | non-empty, unique, sorted values from `gene` |
| Protocol-labelled OMIM AD seeds | `phase3_network.md`; embedded vector, no database fields | {len(OMIM_PROTOCOL_SEEDS)} / {len(set(OMIM_PROTOCOL_SEEDS))} | UNKNOWN as an independently reproducible OMIM extraction: no raw E-utilities response, OMIM phenotype/gene IDs, query, retrieval date, or per-gene evidence file was found locally | retained as pre-specified protocol-curated seeds; not represented as a newly verified OMIM set |
| Protocol uremic-mechanism seeds | `phase3_network.md`; embedded vector, no citation fields | {len(UREMIC_PROTOCOL_SEEDS)} / {len(set(UREMIC_PROTOCOL_SEEDS))} | UNKNOWN as literature curation: no PMID/DOI, evidence type, direction, tissue/species, or per-gene citation table was found locally | retained as pre-specified protocol-curated seeds; not represented as independently verified mechanisms |

The protocol's expected union size of 40–60 is incompatible with the actual Phase 1 intersection alone ({len(geo)} genes). It is therefore a diagnostic expectation, not an acceptance threshold. The {len(OMIM_PROTOCOL_SEEDS)} OMIM-labelled seeds add {len(omim_novel)} genes beyond Phase 1; the {len(UREMIC_PROTOCOL_SEEDS)} uremic seeds add {len(uremic_novel)} beyond Phase 1 (source overlaps are shown in the membership table).

## Interpretation boundary

Membership in this union is input provenance, not evidence of causal mediation or therapeutic action. Phase 2 MVMR estimates conditional direct effects and does not prove mediation. Future PPI degree or betweenness ranks describe the chosen network and must not be used to infer causality.

## Input fingerprints

- Phase 1 intersection SHA-256: `{sha256(geo_path)}`
- Phase 1 generator SHA-256: `{sha256(root / 'project/scripts/phase1_mapping_enrichment.R')}`
- Phase 3 protocol SHA-256: `{sha256(protocol_path)}`
"""
    (output_dir / "PHASE3_GENESET_AUDIT.md").write_text(report, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    args = parser.parse_args()
    write_outputs(args.root.resolve())


if __name__ == "__main__":
    main()
